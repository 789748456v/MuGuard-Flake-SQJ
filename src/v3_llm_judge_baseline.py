CACHE_LOCK = threading.Lock()


JUDGE_SYSTEM_PROMPT = """You are a strict, impartial software testing auditor checking whether a candidate flaky-test repair silently erodes the test's fault-detection oracle.

Determine whether the patched test preserves the original test's fault-detection power over production code, OR silently weakens/shifts it.

Classify as EROSION_DETECTED if the patch:
- Weakens exact equality/completeness checks into partial substring, key-only, non-empty, or weaker assertions;
- Normalizes delimiters/formats in a way that drops edge cases (e.g., split(",") dropping trailing empty tokens);
- Shrinks/simplifies input fixtures or preconditions so production branches are no longer exercised;
- Resets/clobbers shared state after test actions or alters partner tests in a way that drops checks;
- Mocks, stubs, or bypasses the real production call under test;
- Replaces the original tested output/behavior with a different object or weaker property (responsibility shift).

Classify as SAFE_PASS ONLY if the patch solely removes nondeterminism (e.g., deterministic ordering/sorting of unordered collections/JSON, clean fixture isolation before setup, deterministic test-only state cleanup) while preserving all original production fault-detection invariants.

Return STRICT JSON ONLY with keys:
{
  "verdict": "SAFE_PASS" | "EROSION_DETECTED",
  "category": "LEGITIMATE_CANONICALIZATION" | "GENUINE_ORACLE_WEAKENING" | "TEST_RESPONSIBILITY_SHIFT",
  "confidence": 1 | 2 | 3,
  "reason": "One concise sentence explaining what production behavior or assertion invariant is preserved or lost.",
  "repair_guidance": "If EROSION_DETECTED, one concise actionable instruction to fix flakiness without losing the check; else empty string."
}"""


def make_diff(a: str, b: str, name: str) -> str:
    return "\n".join(
        difflib.unified_diff(
            (a or "").splitlines(),
            (b or "").splitlines(),
            fromfile=f"orig/{name}",
            tofile=f"patched/{name}",
            lineterm="",
            n=3,
        )
    )


def load_cache() -> Dict[str, Any]:
    if CACHE_PATH.exists():
        try:
            return json.loads(CACHE_PATH.read_text(encoding="utf-8"))
        except Exception:
            pass
    return {}


def save_cache(cache: Dict[str, Any]) -> None:
    tmp = CACHE_PATH.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(cache, ensure_ascii=False, indent=1), encoding="utf-8")
    tmp.replace(CACHE_PATH)


def parse_judge_json(raw: str) -> Dict[str, Any]:
    txt = (raw or "").strip()
    m = re.search(r"\{.*\}", txt, re.DOTALL)
    if m:
        try:
            obj = json.loads(m.group(0))
            verdict = str(obj.get("verdict", "")).upper().strip()
            if verdict in ("SAFE_PASS", "EROSION_DETECTED"):
                return {
                    "verdict": verdict,
                    "category": str(obj.get("category", "")).upper().strip(),
                    "confidence": int(obj.get("confidence", 2)),
                    "reason": str(obj.get("reason", "")).strip()[:400],
                    "repair_guidance": str(obj.get("repair_guidance", "")).strip()[:400],
                    "parse_ok": True,
                }
        except Exception:
            pass
    # Fallback regex
    verdict = "EROSION_DETECTED" if "EROSION_DETECTED" in txt.upper() else ("SAFE_PASS" if "SAFE_PASS" in txt.upper() else "PARSE_ERROR")
    return {
        "verdict": verdict,
        "category": "",
        "confidence": 1,
        "reason": txt[:300],
        "repair_guidance": "",
        "parse_ok": verdict in ("SAFE_PASS", "EROSION_DETECTED"),
    }


def build_full_pr_unified_diff(
    sample: Dict[str, Any],
    pr_entry: Dict[str, Any],
    pr_diff_cache: Dict[str, str],
    max_chars: int = 16000,
) -> str:
    """
    Extract the complete PR test-file unified diff (prioritizing target test file,
    partner test file, and then any shared fixture/helper test files in the PR) so
    class-level @Before/@After, shared fixtures, imports, and helper edits are 100% visible.
    """
    pr_url = (pr_entry.get("pr_url") or sample.get("pr_url") or "").strip().rstrip("/")
    slug = re.sub(r"[^A-Za-z0-9_.-]+", "_", pr_url) + ".diff"
    raw = pr_diff_cache.get(slug, "")
    idx_git = raw.find("diff --git ")
    clean = raw[idx_git:].strip() if idx_git >= 0 else raw.strip()
    if not clean:
        return ""

    vic_rel = (sample.get("victim_file_rel") or "").replace("\\", "/").lstrip("/")
    pol_rel = (sample.get("polluter_file_rel") or "").replace("\\", "/").lstrip("/")

    parts = re.split(r"(?=^diff --git )", clean, flags=re.M)
    pri_vic, pri_pol, others = [], [], []
    for sec in parts:
        s = sec.strip()
        if not s:
            continue
        m = re.match(r"diff --git a/(\S+)\s+b/(\S+)", s)
        f_rel = m.group(2) if m else ""
        if vic_rel and (f_rel.endswith(vic_rel) or vic_rel.endswith(f_rel)):
            pri_vic.append(s)
        elif pol_rel and pol_rel != vic_rel and (f_rel.endswith(pol_rel) or pol_rel.endswith(f_rel)):
            pri_pol.append(s)
        else:
            others.append(s)

    ordered = "\n\n".join(pri_vic + pri_pol + others)
    if len(ordered) > max_chars:
        ordered = ordered[:max_chars] + "\n... [truncated remaining lines of large multi-file PR diff]"
    return ordered


def call_judge_cached(
    cache: Dict[str, Any],
    judge_model: str,
    lang: str,
    flaky_type: str,
    test_name: str,
    orig_t: str,
    cand_t: str,
    orig_p: str = "",
    cand_p: str = "",
    extra_context: str = "",
    purpose: str = "v3_llm_judge",
    full_pr_diff: str = "",
) -> Dict[str, Any]:
    ext = "java" if lang == "java" else "py"
    t_diff = make_diff(orig_t, cand_t, f"target.{ext}")
    p_diff = make_diff(orig_p, cand_p, f"partner.{ext}") if (orig_p and cand_p and orig_p.strip() != cand_p.strip()) else ""
    if full_pr_diff:
        method_note = (
            "(Unchanged method body; PR modifies @Before/@After class fixtures, imports, partner, or shared test helpers — inspect COMPLETE PR TEST-FILE UNIFIED DIFF below)"
            if not t_diff.strip()
            else t_diff[:4000]
        )
        user_msg = (
            f"Language: {lang} | Flaky Type: {flaky_type} | Test: {test_name}\n"
            f"{extra_context}\n"
            f"=== ORIGINAL TARGET TEST METHOD ===\n{(orig_t or '')[:4000]}\n\n"
            f"=== CANDIDATE PATCHED TARGET TEST METHOD ===\n{(cand_t or '')[:4000]}\n\n"
            f"=== TARGET METHOD DIFF ===\n{method_note}\n\n"
            f"=== COMPLETE PR TEST-FILE UNIFIED DIFF (Target Class, @Before/@After Fixtures, Partner, Imports, & Helpers) ===\n{full_pr_diff}\n"
        )
    else:
        user_msg = (
            f"Language: {lang} | Flaky Type: {flaky_type} | Test: {test_name}\n"
            f"{extra_context}\n"
            f"=== ORIGINAL TARGET TEST ===\n{(orig_t or '')[:4000]}\n\n"
            f"=== CANDIDATE PATCHED TARGET TEST ===\n{(cand_t or '')[:4000]}\n\n"
            f"=== TARGET UNIFIED DIFF ===\n{t_diff[:4000]}\n"
        )
        if p_diff:
            user_msg += f"\n=== PARTNER TEST DIFF ===\n{p_diff[:3000]}\n"

    key_raw = f"v3judge|{judge_model}|{user_msg}"
    ckey = hashlib.sha256(key_raw.encode("utf-8")).hexdigest()[:24]

    with CACHE_LOCK:
        if ckey in cache and cache[ckey].get("parse_ok"):
            return dict(cache[ckey], cached=True)

    extra_body = None
    max_tok = 1024
    if judge_model.startswith("qwen"):
        # Fast non-bloated reasoning budget for structured JSON audit
        extra_body = {"enable_thinking": True, "thinking_budget": 2048}
        max_tok = 3072
    elif judge_model == "glm-5":
        extra_body = {"enable_thinking": True, "thinking_budget": 2048}
        max_tok = 3072
    elif judge_model == "deepseek-flash":
        max_tok = 4096
    elif judge_model == "deepseek-v4-pro":
        max_tok = 4096

    last_err = ""
    for attempt in range(3):
        try:
            resp = chat_completion(
                provider=None,
                model=judge_model,
                messages=[
                    {"role": "system", "content": JUDGE_SYSTEM_PROMPT},
                    {"role": "user", "content": user_msg},
                ],
                temperature=0.0,
                max_tokens=max_tok,
                purpose=purpose,
                timeout=180,
                extra_body=extra_body,
            )
            parsed = parse_judge_json(resp["content"])
            parsed["judge_model"] = judge_model
            parsed["latency_sec"] = resp["latency_sec"]
            parsed["prompt_tokens"] = (resp.get("usage") or {}).get("prompt_tokens", 0)
            parsed["completion_tokens"] = (resp.get("usage") or {}).get("completion_tokens", 0)
            if parsed["parse_ok"]:
                with CACHE_LOCK:
                    cache[ckey] = parsed
                return dict(parsed, cached=False)
            last_err = f"parse_failed: {resp['content'][:120]}"
        except Exception as e:
            last_err = str(e)[:200]
            time.sleep(2 * (attempt + 1))

    return {
        "verdict": "PARSE_ERROR",
        "category": "",
        "confidence": 0,
        "reason": last_err,
        "repair_guidance": "",
        "parse_ok": False,
        "judge_model": judge_model,
        "latency_sec": 0.0,
        "cached": False,
    }


def cross_vendor_judge_for(gen_model: str) -> str:
    """
    Strictly cross-vendor pairing across independent providers:
      - DeepSeek / Moonshot / Zhipu patches -> judged by Alibaba `qwen3.7-plus`
      - Alibaba `qwen3.7-plus` patches      -> judged by Zhipu `glm-5`
    """
    m = (gen_model or "").lower()
    if m.startswith("qwen"):
        return "glm-5"
    return "qwen3.7-plus"


def run_pr_and_eroded400(workers: int = 6) -> None:
    cache = load_cache()
    bm = json.loads((DATA_DIR / "v2_frozen_benchmark_light.json").read_text(encoding="utf-8"))
    bm_by_id = {s["sample_id"]: s for s in bm["samples"]}

    # Build lookup for all 400 eroded patches
    from build_v3_human_audit_pack import build_candidate_lookup
    by_cand_key, by_unique_key = build_candidate_lookup(bm_by_id)

    # 1. All 43 W+-passing test-only Java PRs judged by BOTH qwen3.7-plus AND glm-5 with COMPLETE PR test-file unified diff!
    pr_man = json.loads((DATA_DIR / "pr_reference_manifest.json").read_text(encoding="utf-8"))["entries"]
    pr_adj = json.loads((DATA_DIR / "pr_independent_adjudication_input.json").read_text(encoding="utf-8"))["entries"]
    pr_diff_cache = json.loads((DATA_DIR / "v3_pr_diff_cache.json").read_text(encoding="utf-8"))
    pr_43 = [
        e for e in pr_man
        if e.get("pr_apply_outcome") == "CLEAN_FULL_TEST_APPLY"
        and e.get("pr_scope_type") == "TEST_ONLY_PR"
        and e.get("w_plus_passed")
    ]
    print(f"[Phase 1A] Judging {len(pr_43)} W+-passing test-only Java PRs (with full PR test-file diffs) using BOTH qwen3.7-plus and glm-5...")

    pr_jobs = []
    for e in pr_43:
        sid = e["sample_id"]
        s = bm_by_id[sid]
        full_pr_diff = build_full_pr_unified_diff(s, e, pr_diff_cache)
        assert full_pr_diff, f"Empty PR diff for {sid} ({e.get('pr_url')})"
        for jm in ("qwen3.7-plus", "glm-5"):
            pr_jobs.append((sid, jm, s, e, full_pr_diff))

    pr_results: Dict[str, Dict[str, Any]] = defaultdict(dict)
    with ThreadPoolExecutor(max_workers=workers) as ex:
        futs = {
            ex.submit(
                call_judge_cached,
                cache,
                jm,
                "java",
                s.get("od_subtype") or s.get("test_type", ""),
                s.get("test_full_name", sid),
                s.get("orig_test_code", ""),
                e.get("applied_victim_code", ""),
                s.get("orig_polluter_code", ""),
                e.get("applied_polluter_code", ""),
                "",
                f"v3_pr_judge_fulldiff_{jm}",
                full_pr_diff,
            ): (sid, jm)
            for sid, jm, s, e, full_pr_diff in pr_jobs
        }
        done_n = 0
        for fut in as_completed(futs):
            sid, jm = futs[fut]
            pr_results[sid][jm] = fut.result()
            done_n += 1
            if done_n % 15 == 0 or done_n == len(futs):
                with CACHE_LOCK:
                    save_cache(cache)
                print(f"  PR judge progress: {done_n}/{len(futs)}", flush=True)

    # Compute PR metrics: each Judge standalone + Hybrid (MuGuard + Judge override on MuGuard-rejected PRs!)
    pr_summary: Dict[str, Any] = {}
    for jm in ("qwen3.7-plus", "glm-5"):
        merged_rej = merged_tot = 0
        legit_rej = 0
        legit_tot = 0
        weak_caught = 0
        weak_tot = 0
        shift_caught = 0
        shift_tot = 0
        # Hybrid: accept if MuGuard accepts OR (MuGuard rejects AND Judge says SAFE_PASS)
        hyb_legit_rej = 0
        hyb_weak_caught = 0
        hyb_shift_caught = 0
        latencies = []
        for e in pr_43:
            sid = e["sample_id"]
            adj = pr_adj.get(sid) or {}
            is_legit = bool(adj.get("is_legitimate_repair"))
            lbl = adj.get("label", "")
            jr = pr_results[sid][jm]
            j_rej = (jr.get("verdict") != "SAFE_PASS")
            mg_rej = not bool(e.get("pr_full_gate_accepts"))
            hyb_rej = mg_rej and j_rej
            if jr.get("latency_sec"):
                latencies.append(jr["latency_sec"])
            if e.get("idoft_status") == "Accepted":
                merged_tot += 1
                if j_rej:
                    merged_rej += 1
            if is_legit:
                legit_tot += 1
                if j_rej:
                    legit_rej += 1
                if hyb_rej:
                    hyb_legit_rej += 1
            elif lbl == "GENUINE_ORACLE_WEAKENING":
                weak_tot += 1
                if j_rej:
                    weak_caught += 1
                if hyb_rej:
                    hyb_weak_caught += 1
            elif lbl == "TEST_RESPONSIBILITY_SHIFT":
                shift_tot += 1
                if j_rej:
                    shift_caught += 1
                if hyb_rej:
                    hyb_shift_caught += 1
        ls_rej = legit_rej + shift_caught
        ls_tot = legit_tot + shift_tot
        pr_summary[jm] = {
            "standalone_judge": {
                "merged_rej": f"{merged_rej}/{merged_tot} ({merged_rej/max(1,merged_tot)*100:.1f}%)",
                "legit_false_rej": f"{legit_rej}/{legit_tot}",
                "legit_false_rej_pct": round(legit_rej / max(1, legit_tot) * 100, 2),
                "legit_plus_shift_rej": f"{ls_rej}/{ls_tot} ({ls_rej/max(1,ls_tot)*100:.1f}%)",
                "weakening_caught": f"{weak_caught}/{weak_tot}",
                "weakening_caught_with_pct": f"{weak_caught}/{weak_tot} ({weak_caught/max(1,weak_tot)*100:.0f}%)",
                "shift_caught": f"{shift_caught}/{shift_tot}",
            },
            "hybrid_muguard_plus_judge_triage": {
                "legit_false_rej": f"{hyb_legit_rej}/{legit_tot}",
                "legit_false_rej_pct": round(hyb_legit_rej / max(1, legit_tot) * 100, 2),
                "weakening_caught": f"{hyb_weak_caught}/{weak_tot}",
                "shift_caught": f"{hyb_shift_caught}/{shift_tot}",
            },
            "median_judge_sec": round(sorted(latencies)[len(latencies) // 2], 2) if latencies else 0.0,
        }

    # 2. All 400 unique eroded patches judged strictly cross-vendor!
    tax_cb = json.loads((DATA_DIR / "taxonomy_audit_codebook.json").read_text(encoding="utf-8"))["entries"]
    eroded_jobs = []
    for e in tax_cb:
        uk = e["unique_patch_key"]
        sid = e["sample_id"]
        tail_fp = uk.split("::")[-1]
        rec = by_unique_key.get(uk) or by_cand_key.get(f"{sid}::{tail_fp}")
        if not rec:
            continue
        jm = cross_vendor_judge_for(e.get("first_seen_model", ""))
        eroded_jobs.append((uk, jm, e, rec))

    print(f"[Phase 1A] Judging {len(eroded_jobs)}/400 unique eroded patches strictly cross-vendor...")
    eroded_results: Dict[str, Dict[str, Any]] = {}
    with ThreadPoolExecutor(max_workers=workers) as ex:
        futs = {
            ex.submit(
                call_judge_cached,
                cache,
                jm,
                rec["language"],
                rec.get("od_subtype", ""),
                rec.get("test_full_name", rec["sample_id"]),
                rec["orig_test_code"],
                rec["cand_test_code"],
                rec.get("orig_partner_code", ""),
                rec.get("cand_partner_code", ""),
                "",
                f"v3_eroded400_judge_{jm}",
            ): (uk, e)
            for uk, jm, e, rec in eroded_jobs
        }
        done_n = 0
        for fut in as_completed(futs):
            uk, e = futs[fut]
            eroded_results[uk] = fut.result()
            done_n += 1
            if done_n % 25 == 0 or done_n == len(futs):
                with CACHE_LOCK:
                    save_cache(cache)
                print(f"  Eroded-400 judge progress: {done_n}/{len(futs)}", flush=True)

    # Summarize 400-patch cross-vendor LLM-Judge detection by mechanism & language!
    by_mech = defaultdict(lambda: {"total": 0, "judge_detected": 0, "judge_missed": 0, "parse_err": 0, "b3p_detected": 0})
    by_lang = defaultdict(lambda: {"total": 0, "judge_detected": 0, "judge_missed": 0})
    tot_eval = 0
    tot_det = 0
    tot_miss = 0
    lats_all = []
    for uk, jm, e, rec in eroded_jobs:
        jr = eroded_results[uk]
        mech = (e.get("coding") or {}).get("primary_mechanism", "UNKNOWN")
        lang = rec["language"]
        tot_eval += 1
        by_mech[mech]["total"] += 1
        by_lang[lang]["total"] += 1
        if not e.get("passes_b3_plus"):
            by_mech[mech]["b3p_detected"] += 1
        if jr.get("latency_sec"):
            lats_all.append(jr["latency_sec"])
        if jr.get("verdict") == "EROSION_DETECTED":
            tot_det += 1
            by_mech[mech]["judge_detected"] += 1
            by_lang[lang]["judge_detected"] += 1
        elif jr.get("verdict") == "SAFE_PASS":
            tot_miss += 1
            by_mech[mech]["judge_missed"] += 1
            by_lang[lang]["judge_missed"] += 1
        else:
            by_mech[mech]["parse_err"] += 1

    eroded_summary = {
        "total_evaluated": tot_eval,
        "judge_detected": tot_det,
        "judge_missed_leaked": tot_miss,
        "detection_recall_pct": round(tot_det / max(1, tot_eval) * 100, 2),
        "bypass_rate_pct": round(tot_miss / max(1, tot_eval) * 100, 2),
        "median_judge_sec": round(sorted(lats_all)[len(lats_all) // 2], 2) if lats_all else 0.0,
        "by_mechanism": {
            m: {
                **v,
                "judge_recall_pct": round(v["judge_detected"] / max(1, v["total"]) * 100, 2),
                "judge_bypass_pct": round(v["judge_missed"] / max(1, v["total"]) * 100, 2),
                "b3p_recall_pct": round(v["b3p_detected"] / max(1, v["total"]) * 100, 2),
            }
            for m, v in sorted(by_mech.items())
        },
        "by_language": {
            l: {**v, "judge_recall_pct": round(v["judge_detected"] / max(1, v["total"]) * 100, 2)}
            for l, v in sorted(by_lang.items())
        },
    }

    out = {
        "protocol_version": "3.0.0-cross-vendor-llm-judge-offline-and-pr",
        "pr_43_summary": pr_summary,
        "eroded_400_summary": eroded_summary,
        "pr_43_records": dict(pr_results),
        "eroded_400_records": eroded_results,
    }
    OUT_OFFLINE.write_text(json.dumps(out, indent=2, ensure_ascii=False), encoding="utf-8")
    save_cache(cache)

    print("\n=== CROSS-VENDOR LLM-JUDGE SUMMARY (43 PRs) ===")
    print(json.dumps(pr_summary, indent=2))
    print("\n=== CROSS-VENDOR LLM-JUDGE SUMMARY (400 ERODED PATCHES) ===")
    print(json.dumps(eroded_summary, indent=2))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=6)
    args = ap.parse_args()
    run_pr_and_eroded400(workers=args.workers)
